function renderPublications() {
  const container = document.getElementById('publications-grid');
  if (!container) return;

  container.innerHTML = dataPaperCards.map(paper => {
    // Build individual resource action pills conditionally
    const pdfBtn = paper.pdfFile ? `<a href="${paper.pdfFile}" class="w3-button pub-mini-btn" target="_blank" style="border: 1px solid var(--cyan); background: rgba(24, 228, 255, 0.04); color: var(--cyan);">PDF</a>` : '';
    const videoBtn = paper.videoLink ? `<a href="${paper.videoLink}" class="w3-button pub-mini-btn" target="_blank" style="border: 1px solid var(--pink); background: rgba(255, 61, 242, 0.04); color: var(--pink);">Video</a>` : '';
    const codeBtn = paper.codeLink ? `<a href="${paper.codeLink}" class="w3-button pub-mini-btn" target="_blank" style="border: 1px solid var(--lime); background: rgba(184, 255, 94, 0.04); color: var(--lime);">Code</a>` : '';
    const dataBtn = paper.dataLink ? `<a href="${paper.dataLink}" class="w3-button pub-mini-btn" target="_blank" style="border: 1px solid var(--yellow); background: rgba(254, 254, 51, 0.04); color: var(--yellow);">Data</a>` : '';
    const appBtn = paper.appLink ? `<a href="${paper.appLink}" class="w3-button pub-mini-btn" target="_blank" style="border: 1px solid var(--amber); background: rgba(255, 184, 77, 0.04); color: var(--amber);">App</a>` : '';
    
    // W3.CSS Dropdown Cite Panel
    const citeBtn = paper.citation ? `
      <div class="w3-dropdown-hover" style="background: transparent;">
        <button class="w3-button pub-mini-btn" style="border: 1px solid var(--muted); background: rgba(167, 180, 200, 0.04); color: var(--muted);">Cite</button>
        <div class="w3-dropdown-content w3-card-4 cite-dropdown-panel">
          <p class="cite-text">${paper.citation}</p>
        </div>
      </div>
    ` : '';

    return `
      <article class="panel pub-compact-card">
        <div>
          <div class="pub-compact-thumb">
            <img src="${paper.graphicalAbstract || 'assets/default-pub.svg'}" alt="${paper.paperShortInfo}" loading="lazy" decoding="async">
          </div>
          
          <div style="font-size: 0.72rem; font-weight: 800; text-transform: uppercase; letter-spacing: 0.02em; margin-bottom: 4px; display: flex; justify-content: space-between; flex-wrap: wrap; gap: 4px;">
            <span style="color: var(--pink); max-width: 100%; overflow: hidden; text-overflow: ellipsis; white-space: nowrap;">${paper.venueYear}</span>
          </div>
          
          <h3 style="font-size: 0.95rem; line-height: 1.25; margin-bottom: 4px; color: var(--ink); font-weight: 700; display: -webkit-box; -webkit-line-clamp: 3; -webkit-box-orient: vertical; overflow: hidden;">
            ${paper.paperShortInfo}
          </h3>
        </div>
        
        <!-- Final Row: Buttons placed strictly side-by-side -->
        <div style="display: flex; flex-wrap: wrap; gap: 6px; margin-top: auto; padding-top: 8px; border-top: 1px solid rgba(143, 240, 255, 0.08);">
          ${pdfBtn}
          ${videoBtn}
          ${codeBtn}
          ${dataBtn}
          ${appBtn}
          ${citeBtn}
        </div>
      </article>
    `;
  }).join('');
}

document.addEventListener('DOMContentLoaded', renderPublications);
